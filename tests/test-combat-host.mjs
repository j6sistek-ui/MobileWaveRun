import assert from 'node:assert/strict';
import { setImmediate as nextTurn } from 'node:timers/promises';
import { createDom } from './helpers/dom.mjs';

// Real input/Depot/checkpoint integration; synthetic wave handoffs do not claim natural play.
const dom = createDom({ holdImages: true });
const { win, tick, touch } = dom;
const app = win.document.createElement('main');
app.id = 'app'; win.document.body.append(app);
await import('../dist/js/bootstrap.js');
for (let turn = 0; !win.__sandbox && turn < 100; turn++) await nextTurn();
const engine = win.__sandbox;
assert(engine, 'bootstrap creates an engine');
const key = (type, code = 'KeyF', repeat = false, target = win) => target.dispatchEvent(
  new win.KeyboardEvent(type, { code, repeat, bubbles: true, cancelable: true }));
const control = id => {
  const button = app.querySelector(`[data-spill-control="${id}"]`);
  assert(button, `missing control ${id}`); return button;
};
const action = id => {
  const button = app.querySelector(`[data-action="${id}"]`);
  assert(button, `missing action ${id}`); return button;
};
const Spill = await import('../dist/js/spill.js');
const Save = await import('../dist/js/save.js');
const Combat = await import('../dist/js/spill-combat.js');

try {
  key('keydown'); engine.spillFire(true, 'early');
  assert.equal(engine.world.screen, 'title');
  assert.equal(engine.world.spill, null, 'fire cannot launch while art loads');
  dom.releaseImages();
  await engine.artReady;
  for (let turn = 0; !app.querySelector('[data-action="new-run"]') && turn < 100; turn++) await nextTurn();
  key('keyup');
  action('settings').click();
  action('control-guide').click();
  assert(action('control-guide').closest('details').open);
  assert.match(app.textContent, /SECOND FINGER/);
  assert.match(app.textContent, /match their height/);
  action('home').click(); action('new-run').click();
  control('land').click(); tick(200);
  const state = engine.world.spill;
  assert.equal(state.phase, 'depot');
  assert.equal(state.combat.weapon, 'laser');
  assert(state.freeUpgrade);
  assert.equal(control('weapon-upgrade').disabled, true, 'no unaffordable opening upgrade');
  control('weapon-cannon').click();
  assert.equal(state.combat.weapon, 'cannon');
  assert(state.freeUpgrade, 'free weapon selection does not consume the system choice');
  assert.equal(state.ore, 0);
  assert.equal(Save.loadSave().spillSuspended.state.combat.weapon, 'cannon', 'selection checkpoints immediately');
  assert.match(app.querySelector('.ac-workshop-weapons').textContent, /4 damage/);
  key('keydown');
  assert.equal(state.combat.firing, false, 'Depot cannot arm queued firing');
  control('weapon-laser').click();
  control('inspect-thrusters').click(); control('thrusters').click(); control('launch').click();
  assert.equal(state.phase, 'countdown');
  key('keydown');
  tick(181);
  assert.equal(state.phase, 'wave');
  assert.equal(state.combat.firing, false, 'holding during countdown never fires on launch');
  key('keyup');
  const stick = app.querySelector('.ac-floating-stick');
  assert(stick && stick.hidden);
  assert.equal(app.querySelector('.ac-fire, .ac-thrust, .ac-spillcontrols'), null);
  const keepClear = () => {
    state.pilot.y = state.H * .4; state.pilot.vy = 0; state.floorT = 0;
    state.iframes = 10; state.rocks = []; state.nuts = [];
  };
  keepClear();
  const before = state.combat.nextId;
  key('keydown'); tick();
  assert.equal(state.combat.nextId, before + 1);
  key('keydown', 'KeyF', true);
  assert.equal(state.combat.nextId, before + 1, 'OS repeats do not emit shots');
  tick(20);
  assert(state.combat.nextId >= before + 3, 'held keyboard fire repeats through the fixed clock');
  key('keyup');

  touch(engine.canvas, 'pointerdown', 1, 100, 300, false);
  touch(engine.canvas, 'pointermove', 1, 100, 250, false);
  assert.equal(state.steerY, -1);
  tick(); assert(!stick.hidden);
  assert.equal(stick.style.left, `${100 / 390 * 100}%`);
  assert.equal(stick.style.top, `${300 / 760 * 100}%`);
  state.combat.cooldown = 0;
  const tapId = state.combat.nextId;
  touch(engine.canvas, 'pointerdown', 2, 330, 690, false);
  touch(win, 'pointerup', 2);
  assert.equal(state.combat.firing, false);
  tick();
  assert.equal(state.combat.nextId, tapId + 1, 'second-finger tap between frames is not lost');
  assert.equal(state.steerY, -1, 'firing does not steal steering');
  touch(engine.canvas, 'pointerdown', 3, 330, 690, false);
  key('keydown'); key('keyup');
  assert(state.combat.firing, 'keyboard release preserves a held firing finger');
  touch(win, 'pointerup', 99);
  assert(state.combat.firing);
  touch(win, 'pointerup', 1);
  assert.equal(state.steerY, 0);
  assert.equal(engine.spillControls().active, false);
  touch(engine.canvas, 'pointermove', 3, 330, 500, false);
  assert.equal(state.steerY, 0, 'held firing finger is never promoted to steering');
  touch(win, 'pointerup', 3);
  assert.equal(state.combat.firing, false);

  state.combat.cooldown = 0;
  state.pilot.vy = 0;
  const spaceId = state.combat.nextId, yBeforeSpace = state.pilot.y;
  key('keydown', 'Space'); key('keyup', 'Space'); tick();
  assert.equal(state.combat.nextId, spaceId + 1, 'Space tap fires between frames');
  assert.equal(state.pilot.y, yBeforeSpace, 'Space no longer applies a flight kick');
  key('keydown', 'KeyW'); assert.equal(state.steerY, -1);
  key('keydown', 'ArrowUp'); key('keyup', 'KeyW'); assert.equal(state.steerY, -1);
  key('keydown', 'KeyS'); assert.equal(state.steerY, 0);
  key('keyup', 'ArrowUp'); assert.equal(state.steerY, 1);
  key('keyup', 'KeyS'); assert.equal(state.steerY, 0);
  key('keydown', 'ControlLeft'); key('keyup', 'ControlLeft');
  assert.equal(state.steerY, 0, 'obsolete dive keys cannot create an unreleased steering axis');
  state.cool = 0; state.lungeCharges = 1;
  key('keydown', 'KeyA'); assert.equal(state.lungeDir, -1); key('keyup', 'KeyA');
  state.cool = 0; state.lungeCharges = 1;
  key('keydown', 'ArrowRight'); assert.equal(state.lungeDir, 1); key('keyup', 'ArrowRight');
  state.lunge = 0; state.pilot.vx = 0;

  touch(engine.canvas, 'pointerdown', 4, 100, 300);
  tick(75); // stationary hold before the flick, sampled by the real frame loop
  state.cool = 0; state.lungeCharges = 1;
  touch(engine.canvas, 'pointermove', 4, 150, 302);
  assert.equal(state.lungeDir, 1); assert(state.lunge > 0, 'flick still works after a long hold');
  state.lunge = 0; state.pilot.vx = 0;
  tick(20); state.cool = 0; state.lungeCharges = 1;
  touch(engine.canvas, 'pointermove', 4, 95, 300);
  assert.equal(state.lungeDir, -1);
  touch(win, 'pointerup', 4);
  state.lunge = 0; state.pilot.vx = 0;
  for (const type of ['touchstart', 'touchmove', 'touchend', 'gesturestart', 'gesturechange', 'gestureend']) {
    const event = new win.Event(type, { bubbles: true, cancelable: true });
    engine.canvas.dispatchEvent(event);
    assert(event.defaultPrevented, `${type} cannot zoom the active play surface`);
  }

  key('keydown', 'KeyW'); key('keydown'); action('pause').click();
  assert.equal(state.combat.firing, false); assert.equal(state.steerY, 0);
  const paused = JSON.stringify(state);
  tick(90); key('keydown', 'KeyF', true); key('keydown', 'KeyW', true);
  assert.equal(JSON.stringify(state), paused);
  action('resume').click();
  key('keydown', 'KeyF', true); key('keydown', 'KeyW', true);
  assert.equal(state.combat.firing, false); assert.equal(state.steerY, 0);
  key('keyup'); key('keyup', 'KeyW');
  touch(engine.canvas, 'pointerdown', 5, 100, 300);
  touch(engine.canvas, 'pointermove', 5, 100, 350);
  touch(engine.canvas, 'pointerdown', 6, 330, 690, false);
  touch(engine.canvas, 'lostpointercapture', 5);
  assert.equal(state.steerY, 0); assert.equal(state.combat.firing, false);
  assert.equal(engine.spillControls().active, false);
  touch(engine.canvas, 'pointermove', 5, 100, 220);
  assert.equal(state.steerY, 0, 'stale movement cannot reacquire cancelled control');
  key('keydown'); key('keydown', 'KeyW');
  win.dispatchEvent(new win.Event('blur'));
  assert.equal(engine.world.screen, 'pause');
  assert.equal(state.combat.firing, false); assert.equal(state.steerY, 0);
  engine.resume(); key('keyup'); key('keyup', 'KeyW'); key('keydown'); key('keydown', 'KeyW');
  Object.defineProperty(win.document, 'hidden', { value: true, configurable: true });
  win.document.dispatchEvent(new win.Event('visibilitychange'));
  assert.equal(engine.world.screen, 'pause');
  assert.equal(state.combat.firing, false); assert.equal(state.steerY, 0);
  Object.defineProperty(win.document, 'hidden', { value: false, configurable: true });
  engine.resume(); key('keyup'); key('keyup', 'KeyW'); key('keydown'); key('keydown', 'KeyW');
  dom.setWidth(320); engine.resize();
  assert.equal(engine.world.screen, 'pause');
  assert.equal(state.combat.firing, false); assert.equal(state.steerY, 0);
  engine.resume(); key('keyup'); key('keyup', 'KeyW');
  key('keydown'); key('keydown', 'KeyW'); engine.stop();
  assert.equal(state.combat.firing, false); assert.equal(state.steerY, 0);
  key('keyup'); key('keydown');
  assert.equal(state.combat.firing, false);
  engine.start(); key('keyup'); key('keyup', 'KeyW');

  keepClear();
  state.wave = 4; state.spec = Spill.spillWaveSpec(4, state.seed); state.phase = 'drain';
  state.combat.enemies = []; state.combat.shots = [];
  touch(engine.canvas, 'pointerdown', 7, 100, 300);
  touch(engine.canvas, 'pointermove', 7, 100, 250);
  key('keydown'); tick();
  assert.equal(state.phase, 'countdown');
  assert.equal(engine.spillControls().active, false, 'a new wave countdown releases the old finger');
  assert.equal(state.steerY, 0); assert.equal(state.combat.firing, false);
  touch(engine.canvas, 'pointermove', 7, 100, 350);
  assert.equal(state.steerY, 0);
  key('keyup'); key('keydown', 'KeyW');
  assert.equal(state.steerY, -1, 'a fresh steering press can take manual control during countdown');
  tick(181);
  assert.equal(state.phase, 'wave');
  assert.equal(state.steerY, -1, 'manual countdown steering survives GO');
  key('keyup', 'KeyW');
  keepClear();
  state.wave = 5; state.spec = Spill.spillWaveSpec(5, state.seed); state.phase = 'drain';
  state.combat.enemies = []; state.combat.shots = [];
  key('keydown'); tick();
  assert.equal(state.phase, 'docking');
  assert.equal(state.combat.firing, false, 'automatic Depot entry cancels held fire');
  tick(Math.ceil((Spill.SPILL.dockTime + Spill.SPILL.depotArm + .2) * 60)); key('keyup');
  assert.equal(state.phase, 'depot');
  const scrollTouch = new win.Event('touchmove', { bubbles: true, cancelable: true });
  app.querySelector('.ac-depotcard').dispatchEvent(scrollTouch);
  assert(!scrollTouch.defaultPrevented, 'Depot touch scrolling remains available');
  state.ore = 200;
  control('weapon-cannon').click();
  control('weapon-upgrade').click();
  assert.equal(state.combat.levels.cannon, 2);
  assert.equal(state.ore, 135);
  assert.equal(Save.loadSave().spillSuspended.state.combat.levels.cannon, 2, 'purchase checkpoints immediately');
  const stats = Combat.spillWeaponStats(state);
  assert.match(app.querySelector('.ac-workshop-weapons').textContent, new RegExp(`${stats.damage} damage`));
  control('weapon-upgrade').click();
  assert.equal(state.combat.levels.cannon, 3);
  assert.equal(state.ore, 5);
  assert(control('weapon-upgrade').disabled);
  control('save').click(); action('resume-run').click(); tick(50);
  const resumed = engine.world.spill;
  assert.equal(resumed.combat.weapon, 'cannon');
  assert.deepEqual(resumed.combat.levels, { laser: 1, cannon: 3 });
  assert.equal(resumed.combat.firing, false);
  assert.equal(resumed.combat.shots.length, 0);
  control('launch').click(); tick(181);
  assert.equal(resumed.combat.firing, false, 'saved firing never resumes at next wave');
  key('keydown'); engine.open('title');
  assert.equal(resumed.combat.firing, false, 'home navigation releases fire immediately');
  console.log('combat host: loading guard, drag/keyboard steering, flicks, queued taps, zoom guards, pause/focus/resize/stop, Depot selection/upgrades and checkpoint resume passed');
} finally {
  engine.stop();
  await win.happyDOM.close();
}

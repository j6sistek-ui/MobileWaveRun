import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import * as Spill from '../dist/js/spill.js';

// Frozen from AcornautSandbox b67bb50f3f3fa24b6a335133a1c176638a83f775.
// These are extraction guards, not a new balance specification. Change them only when
// deliberately changing the game, with a review explaining the new behavior.
const authority = {
  'spill.ts': 'b4897f2dd82b7aefb73ae4c7c25c424dda2281366141cf97256f552bd2ff6ab7',
  'spill-content.ts': 'eb0a9f34123011d701178c983e314d96850e16e17e848720c4cf6bf08547dd3a',
  'spill-presentation.ts': '5d63ec10df0b0507c2e2fb5406e84e9dfe57b127d2699ea95b239f80cbdca27c',
  'spill-depot-gag.ts': 'e5899a33a6cb8981baa3dd1c6098bb426b27b903306f5ba87d1d4ad3a4ece172',
};
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
for (const [file, expected] of Object.entries(authority)) {
  // Windows Git checkouts use CRLF; normalize only line endings to the committed LF bytes.
  const source = readFileSync(new URL(`../illustrated-src/game/${file}`, import.meta.url), 'utf8').replaceAll('\r\n', '\n');
  assert.equal(sha256(source), expected, `${file} must preserve the pinned upstream source content`);
}

// Generated by running the pinned upstream docs/js/spill.js, not this extraction.
// Full state includes RNG, debris, pickups, clocks, health and movement. No immunity,
// forced wave transition, spawning override or render dependency is used in these traces.
const traces = [
  [390, 760, 7, 'bf6d41be1eb280ebede7d8683db9324a738f873d5d05bea2a307b222732aaee9'],
  [1280, 720, 71, '7f2da9d463e1c47383cfe8915f535f1096b001154c5ecbcedc3a23824ba2dda2'],
  [320, 760, 305419896, '2ff7a0a1200442a4c10c0fa327c75e95907bce4afd85b0eb5839f8ed5ce7ecf7'],
];
for (const [width, height, seed, expected] of traces) {
  const state = Spill.createSpill(width, height, seed, 0, true, false);
  Spill.spillTap(state);
  for (let frame = 0; frame < 900; frame++) {
    if (frame % 24 === 0) Spill.spillTap(state);
    if (frame === 240) Spill.spillBurst(state, -1);
    if (frame === 480) Spill.spillLunge(state);
    Spill.stepSpill(state, 1 / 60);
  }
  assert.equal(sha256(JSON.stringify(state)), expected,
    `seed ${seed} at ${width}x${height} must match the complete upstream state after 900 simulation frames`);
}
console.log('upstream parity: four LF-normalized source hashes and three deterministic 900-frame traces passed');
